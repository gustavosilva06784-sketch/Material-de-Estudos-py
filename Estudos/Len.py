#"Len" vem de length, que significa "comprimento".
#ele serve para descobrir quantos elementos existem em alguma "coisa".
#se definirmos uma variavel e dentro dela colocarmos itens dentro de parenteses e entre aspas, "Len" ira dizer quantos itens tem dentro do parenteses e que estão entre aspas.
#se definirmos uma variavel e dentro dela apenas colocar um nome ou uma frase apenas entre as aspas (não utilizando os parenteses), "Len" ira Dizer quantas letras tem entre as aspas.
#tambem funciona com numeros.
#"Len" conta elementos existentes, e não os indices.

frutas = ("Maçã", "Uva", "Banana", "Pêra", "Melancia", "Morango")
print(len(frutas))